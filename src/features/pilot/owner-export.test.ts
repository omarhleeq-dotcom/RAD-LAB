import { createHash } from "node:crypto";
import { expect,it } from "vitest";
import { EMPTY_FILTERS, type OwnerPage } from "./owner-data";
import { createOwnerExport, EXPORT_PAGE_SIZE } from "./owner-export";
const time="2026-10-24T09:00:00Z";
const note={id:"1",participant_code:"P-fixture",exam_id:"chest-pa-erect",attempt_id:null,attempt_no:null,text:"ملاحظة عربية\nسطر ثانٍ",at:time};
const attempt={id:"fixture-attempt",participant_code:"P-fixture",attempt_no:1,exam_id:"chest-pa-erect",case_id:"default",definition_version:"fixture",settings:{kvp:110},result:{total:82,passed:true,thresholdMet:true,primaryVariant:"ideal",critical:[],categories:[],checks:[]},locale:"ar",started_at:time,finished_at:time};
const page=(rows:Record<string,unknown>[],total=rows.length,next:OwnerPage["next"]=null):OwnerPage=>({version:1,boundary:time,total,pending:0,rows,next});
const notes=[note,{...note,id:"2",text:"=1+1"},{...note,id:"3",text:'He said "dim", then\nnext'}];
const many=Array.from({length:1000},(_,i)=>({...note,id:String(i+1)}));
const cursor={time,id:"1000"};
const first=()=>page(many,1001,cursor),last=()=>page([{...note,id:"1001"}],1001);
const now=()=>new Date(2026,9,24,12);
// Captured from exportOwnerPart on e853775 before the UI flow changed. Never regenerated by these tests.
const baseline={notes:"3cfc49d9c0b1c3492107471fc7e5f72f261660f8686aaa7ecae37dbcfe9de171",attempts:"a79b1f6b4be8cf70b2ebb92adfc9e1970ee4270ec954019ccd9856beb8fdd222"};
it.each(["notes","attempts"] as const)("one click downloads one %s file with byte-identical pre-change CSV",async stream=>{
 const saved:{name:string;csv:string}[]=[];let reads=0;
 const flow=createOwnerExport({now,read:async()=>{reads++;return page(stream==="notes"?notes:[attempt]);},save:(name,csv)=>saved.push({name,csv})});
 await flow.start(stream,EMPTY_FILTERS);
 expect(reads).toBe(1);expect(saved).toHaveLength(1);expect(saved[0]!.name).toBe(`radlab-${stream}-2026-10-24.csv`);
 expect(createHash("sha256").update(saved[0]!.csv,"utf8").digest("hex")).toBe(baseline[stream]);
 expect(flow.getSnapshot()).toMatchObject({files:1,written:stream==="notes"?3:1,busy:false,complete:true,multipart:false,cursor:null});
 await flow.next();expect(reads).toBe(1);
});
it("downloads part 1 immediately, reads no next page until clicked and preserves the same filters and boundary",async()=>{
 const args:unknown[][]=[],saved:string[]=[];
 const flow=createOwnerExport({now,read:async(...a)=>{args.push(a);return args.length===1?first():last();},save:name=>saved.push(name)});
 const filters={...EMPTY_FILTERS,participant:"internal-do-not-export",participantCode:"P-fixture",exam:"chest-pa-erect",from:"2026-10-17T00:00:00Z"};
 await flow.start("notes",filters);filters.exam="changed-after-start";
 expect(args).toHaveLength(1);expect(saved).toEqual(["radlab-notes-2026-10-24-part-1.csv"]);
 expect(flow.getSnapshot()).toMatchObject({files:1,written:1000,parts:2,multipart:true,complete:false});
 await flow.next();expect(args[1]!.slice(0,4)).toEqual(["notes",{...filters,exam:"chest-pa-erect"},cursor,time]);
 expect(saved).toEqual(["radlab-notes-2026-10-24-part-1.csv","radlab-notes-2026-10-24-part-2.csv"]);
 expect(flow.getSnapshot()).toMatchObject({files:2,written:1001,complete:true,cursor:null});
 expect(JSON.stringify(flow.report())).not.toContain("internal-do-not-export");
 expect(flow.report()).toMatchObject({complete:true,partsSaved:2,written:1001});
});
it("finishes an exact-full final page without an empty extra file",async()=>{
 let reads=0;const saved:string[]=[];
 const flow=createOwnerExport({read:async()=>{reads++;return page(many,EXPORT_PAGE_SIZE,cursor);},save:name=>saved.push(name)});
 await flow.start("notes",EMPTY_FILTERS);await flow.next();
 expect(reads).toBe(1);expect(saved).toHaveLength(1);expect(flow.getSnapshot()).toMatchObject({complete:true,multipart:false,cursor:null});
});
it("aborts an in-flight export and ignores its late result when another download starts",async()=>{
 let resolveOld!:(p:OwnerPage)=>void;const pending=new Promise<OwnerPage>(resolve=>{resolveOld=resolve;});
 const signals:AbortSignal[]=[],saved:string[]=[];
 const flow=createOwnerExport({read:async(...args)=>{signals.push(args[4]);return args[0]==="notes"?pending:page([attempt]);},save:name=>saved.push(name)});
 const old=flow.start("notes",EMPTY_FILTERS);await flow.start("attempts",EMPTY_FILTERS);
 expect(signals[0]!.aborted).toBe(true);resolveOld(page(notes));await old;
 expect(saved).toHaveLength(1);expect(saved[0]).toContain("attempts");expect(flow.getSnapshot()).toMatchObject({stream:"attempts",files:1,written:1,complete:true,busy:false});
});
it("restarts from an unfinished multipart export without requiring an end/reset action",async()=>{
 const reads:string[]=[],saved:string[]=[];
 const flow=createOwnerExport({read:async stream=>{reads.push(stream);return stream==="notes"?first():page([attempt]);},save:name=>saved.push(name)});
 await flow.start("notes",EMPTY_FILTERS);await flow.start("attempts",EMPTY_FILTERS);
 expect(reads).toEqual(["notes","attempts"]);expect(saved).toHaveLength(2);
 expect(flow.getSnapshot()).toMatchObject({stream:"attempts",written:1,files:1,multipart:false,complete:true,cursor:null});
});
it("can retry a failed next part without counting a file that did not download",async()=>{
 let reads=0;const saved:string[]=[];
 const flow=createOwnerExport({read:async()=>{reads++;if(reads===2)throw new Error("fixture failure");return reads===1?first():last();},save:name=>saved.push(name)});
 await flow.start("notes",EMPTY_FILTERS);await flow.next();
 expect(flow.getSnapshot()).toMatchObject({files:1,written:1000,failed:true,complete:false,cursor});
 expect(flow.report().complete).toBe(false);await flow.next();
 expect(saved).toHaveLength(2);expect(flow.getSnapshot()).toMatchObject({files:2,written:1001,failed:false,complete:true});
});
it("does not download after the component is disposed",async()=>{
 let resolve!:(p:OwnerPage)=>void;const pending=new Promise<OwnerPage>(r=>{resolve=r;});let saved=0;
 const flow=createOwnerExport({read:async()=>pending,save:()=>{saved++;}});
 const started=flow.start("notes",EMPTY_FILTERS);flow.dispose();resolve(page(notes));await started;expect(saved).toBe(0);
});
it("counts downloaded records rather than silently claiming skipped items",async()=>{
 const flow=createOwnerExport({read:async()=>page([note,{...note,id:"2",text:""}]),save:()=>{}});
 await flow.start("notes",EMPTY_FILTERS);
 expect(flow.getSnapshot()).toMatchObject({written:1,skipped:1,files:1});expect(flow.report().complete).toBe(false);
});
