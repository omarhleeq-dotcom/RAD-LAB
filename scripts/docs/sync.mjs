export const PENDING_POINTER = "`npm run status:summary -- --pending`";
const canonical = (value) => JSON.stringify(value, (_key, v) => v && typeof v === "object" && !Array.isArray(v) ? Object.fromEntries(Object.entries(v).sort(([a], [b]) => a.localeCompare(b))) : v);
export function syncRevision(data, previous, now = () => new Date()) {
  const currentTasks = [...data.tasks].sort((a, b) => a.id.localeCompare(b.id)), oldTasks = [...previous.tasks].sort((a, b) => a.id.localeCompare(b.id));
  if (canonical(currentTasks) !== canonical(oldTasks) || data.next_id !== previous.next_id) {
    if (data.revision <= previous.revision) data.revision = previous.revision + 1;
    if (Date.parse(data.updated_at) <= Date.parse(previous.updated_at)) data.updated_at = new Date(Math.max(now().getTime(), Date.parse(previous.updated_at) + 1)).toISOString();
  }
  return data;
}
export function pendingPointer(text) {
  const section = /^## (?:الإغلاقات المعلقة|Pending closures)\s*\n([\s\S]*?)(?=^## |$(?![\s\S]))/m.exec(text);
  if (!section) throw new Error("HANDOFF missing pending closures section; define it before docs:sync");
  const body = section[1].trim();
  if (body && !/^`?npm run status:summary(?: -- .*)?`?$/.test(body)) throw new Error("HANDOFF pending section contains prose; replace it with the pending pointer before docs:sync");
  const tail = text.slice(section.index + section[0].length);
  return text.slice(0, section.index) + `## ${section[0].includes("الإغلاقات") ? "الإغلاقات المعلقة" : "Pending closures"}\n\n${PENDING_POINTER}\n${tail ? "\n" : ""}` + tail;
}
export function reportsIndex(root) {
  const folder = path.join(root, "docs/archive/reports"), entries = [];
  function visit(directory) {
    for (const entry of readdirSync(directory, { withFileTypes: true }).sort((a, b) => a.name.localeCompare(b.name, "en"))) {
      const full = path.join(directory, entry.name);
      if (entry.isSymbolicLink()) throw new Error("report index refuses symlinks");
      if (entry.isDirectory()) visit(full);
      else if (entry.name.endsWith(".md") && full !== path.join(folder, "README.md")) entries.push(path.relative(folder, full).split(path.sep).join("/"));
    }
  }
  visit(folder);
  return "# Archived reports\n\n<!-- Generated by npm run docs:sync; filenames only. -->\n\n" + entries.map((name) => `- [${name}](${name.replace(/ /g, "%20")})`).join("\n") + "\n";
}
export function planSync({ root = ROOT, base = "origin/main", head = "HEAD", now = () => new Date() } = {}) {
  const git = (...args) => execFileSync("git", args, { cwd: root, encoding: "utf8", maxBuffer: 16 * 1024 * 1024, stdio: ["ignore", "pipe", "pipe"] });
  const fork = git("merge-base", base, head).trim();
  const files = [...new Set(git("ls-files", "-z", "--cached", "--others", "--exclude-standard").split("\0").filter(Boolean))];
  const changes = git("diff", "--name-status", "-z", "-M", fork).split("\0"), moves = new Map();
  for (let i = 0; i < changes.length && changes[i];) {
    const status = changes[i++], old = changes[i++];
    if (status.startsWith("R")) moves.set(old, changes[i++]);
  }
  const reverse = new Map([...moves].map(([old, current]) => [current, old])), planned = new Map();
  const read = (name) => {
    if (lstatSync(path.join(root, name)).isSymbolicLink()) throw new Error(`docs:sync refuses symlink ${name}`);
    return planned.get(name) ?? readFileSync(path.join(root, name), "utf8");
  };
  function set(name, text) {
    const full = path.join(root, name);
    if (existsSync(full) && lstatSync(full).isSymbolicLink()) throw new Error(`docs:sync refuses symlink ${name}`);
    if (!existsSync(full) || text !== readFileSync(full, "utf8")) planned.set(name, text);
    else planned.delete(name);
  }
  for (const name of files.filter((name) => name.endsWith(".md") && (name.startsWith("docs/") || ["README.md", "AGENTS.md", "CLAUDE.md"].includes(name)) && existsSync(path.join(root, name)))) {
    const text = read(name), old = reverse.get(name) ?? name;
    const previous = old === name ? text : git("show", `${fork}:${old}`);
    set(name, relocateLinks(text, name, moves, { old, previous }));
  }
  const statusName = "docs/project-status.md", statusText = read(statusName), block = extractStatusJson(statusText);
  const previousBlock = extractStatusJson(git("show", `${fork}:${statusName}`));
  if (block.error || previousBlock.error) throw new Error(block.error ?? previousBlock.error);
  const data = JSON.parse(block.json), previous = JSON.parse(previousBlock.json);
  const archiveName = "docs/archive/status-archive.md";
  let archive = read(archiveName);
  for (const task of data.tasks.filter((task) => task.status === "done")) {
    const old = previous.tasks.find((old) => old.id === task.id);
    if (old?.status === "done" && old.description !== task.description) {
      const record = `\n## ${task.id}\n\n\`\`\`\`text\n${old.description}\n\`\`\`\`\n`;
      if (!archive.includes(record)) archive += record;
    }
  }
  const archived = archiveDone(data.tasks, archive);
  data.tasks = archived.tasks; set(archiveName, archived.archive);
  // source_ref is a path pointer; completion_evidence and every other task value
  // remain untouched (except M2 description compaction above).
  for (const task of data.tasks) task.source_ref = task.source_ref.replace(/docs\/[A-Za-z\d_./-]+|(?<![\w/.-])[\w-]+\.md/g, (target) => moves.get(target) ?? (moves.has(`docs/${target}`) ? moves.get(`docs/${target}`) : target));
  const originalData = JSON.parse(block.json);
  syncRevision(data, previous, now);
  if (canonical(data) !== canonical(originalData)) set(statusName, statusText.replace(block.json, JSON.stringify(data, null, 2)));
  set("docs/HANDOFF.md", pendingPointer(read("docs/HANDOFF.md")));
  set("docs/archive/reports/README.md", reportsIndex(root));
  return planned;
}
export function runSync(args = process.argv.slice(2), options = {}) {
  let base = "origin/main", check = false;
  for (let i = 0; i < args.length; i++) {
    if (args[i] === "--base" && args[i + 1]) base = args[++i];
    else if (args[i] === "--check") check = true;
    else throw new Error(`unknown/incomplete option ${args[i]}`);
  }
  const root = options.root ?? ROOT, plan = planSync({ ...options, root, base });
  if (check && plan.size) { console.error(`run npm run docs:sync: stale mechanical fields in ${[...plan.keys()].join(", ")}`); return 1; }
  if (!check) for (const [name, text] of plan) writeFileSync(path.join(root, name), text);
  console.log(`docs:sync: ${plan.size} file(s) ${check ? "stale" : "updated"}`);
  return 0;
}
if (process.argv[1] && path.resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  try { process.exitCode = runSync(); } catch (error) { console.error(`docs:sync: ${error.message}`); process.exitCode = 1; }
}
